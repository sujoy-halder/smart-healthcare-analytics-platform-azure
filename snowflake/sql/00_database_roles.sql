CREATE DATABASE IF NOT EXISTS HEALTHCARE_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE_ANALYTICS.RAW;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE_ANALYTICS.ANALYTICS;

CREATE WAREHOUSE IF NOT EXISTS HEALTHCARE_LOADING_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

CREATE WAREHOUSE IF NOT EXISTS HEALTHCARE_TRANSFORMING_WH
  WAREHOUSE_SIZE = SMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

CREATE ROLE IF NOT EXISTS LOADER;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
CREATE ROLE IF NOT EXISTS ANALYST_READER;

GRANT USAGE ON DATABASE HEALTHCARE_ANALYTICS TO ROLE LOADER;
GRANT USAGE ON SCHEMA HEALTHCARE_ANALYTICS.RAW TO ROLE LOADER;
GRANT CREATE TABLE ON SCHEMA HEALTHCARE_ANALYTICS.RAW TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE HEALTHCARE_LOADING_WH TO ROLE LOADER;

GRANT USAGE ON DATABASE HEALTHCARE_ANALYTICS TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA HEALTHCARE_ANALYTICS.RAW TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA HEALTHCARE_ANALYTICS.ANALYTICS TO ROLE TRANSFORMER;
GRANT CREATE TABLE ON SCHEMA HEALTHCARE_ANALYTICS.ANALYTICS TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE HEALTHCARE_TRANSFORMING_WH TO ROLE TRANSFORMER;

GRANT USAGE ON DATABASE HEALTHCARE_ANALYTICS TO ROLE ANALYST_READER;
GRANT USAGE ON SCHEMA HEALTHCARE_ANALYTICS.ANALYTICS TO ROLE ANALYST_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA HEALTHCARE_ANALYTICS.ANALYTICS TO ROLE ANALYST_READER;
