USE DATABASE HEALTHCARE_ANALYTICS;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS PATIENT_OUTCOMES (
  PATIENT_ID STRING,
  ENCOUNTER_ID STRING,
  DOCTOR_ID STRING,
  HOSPITAL_ID STRING,
  DIAGNOSIS_COUNT NUMBER,
  LAB_RESULT_COUNT NUMBER,
  LAST_CLINICAL_EVENT_AT TIMESTAMP_NTZ,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CLAIMS_ANALYTICS (
  PAYER_ID STRING,
  CLAIM_STATUS STRING,
  CLAIM_COUNT NUMBER,
  TOTAL_BILLED_AMOUNT NUMBER(18, 2),
  AVG_BILLED_AMOUNT NUMBER(18, 2),
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
