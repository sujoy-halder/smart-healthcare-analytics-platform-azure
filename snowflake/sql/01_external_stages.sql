USE DATABASE HEALTHCARE_ANALYTICS;
USE SCHEMA RAW;

CREATE STORAGE INTEGRATION IF NOT EXISTS AZURE_HEALTHCARE_LAKE
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = AZURE
  ENABLED = TRUE
  AZURE_TENANT_ID = '<ENTRA_TENANT_ID>'
  STORAGE_ALLOWED_LOCATIONS = (
    'azure://<ADLS_ACCOUNT_NAME>.blob.core.windows.net/gold/'
  );

DESC STORAGE INTEGRATION AZURE_HEALTHCARE_LAKE;

CREATE FILE FORMAT IF NOT EXISTS JSON_AUTO
  TYPE = JSON
  STRIP_OUTER_ARRAY = FALSE;

CREATE STAGE IF NOT EXISTS GOLD_STAGE
  URL = 'azure://<ADLS_ACCOUNT_NAME>.blob.core.windows.net/gold/'
  STORAGE_INTEGRATION = AZURE_HEALTHCARE_LAKE
  FILE_FORMAT = JSON_AUTO;
