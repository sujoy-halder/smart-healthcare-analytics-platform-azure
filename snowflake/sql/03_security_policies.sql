USE DATABASE HEALTHCARE_ANALYTICS;
USE SCHEMA ANALYTICS;

CREATE MASKING POLICY IF NOT EXISTS MASK_PATIENT_IDENTIFIER AS (val STRING)
  RETURNS STRING ->
    CASE
      WHEN CURRENT_ROLE() IN ('TRANSFORMER') THEN val
      ELSE SHA2(val, 256)
    END;

CREATE ROW ACCESS POLICY IF NOT EXISTS PAYER_ROW_FILTER AS (payer_id STRING)
  RETURNS BOOLEAN ->
    CURRENT_ROLE() IN ('TRANSFORMER', 'ANALYST_READER');
